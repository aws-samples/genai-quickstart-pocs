"""Deployment steps shared by scripts/deploy.sh and scripts/deploy.ps1.

Logic that would otherwise be duplicated in bash and PowerShell lives here,
so both deploy scripts behave the same on macOS, Linux and Windows. Uses
only the Python standard library (plus pip for ``package``).

Subcommands::

    python scripts/deploy_helper.py render-web --outputs web-outputs.json \\
        --templates web/templates --out build/web
"""

import argparse
import json
import shutil
import sys
from pathlib import Path
from typing import Dict, List, Optional

# Stack outputs that the web UI needs, mapped to window.RFP_CONFIG keys.
WEB_CONFIG_OUTPUTS = {
    'ApiGatewayURL': 'apiUrl',
    'CognitoDomain': 'cognitoDomain',
    'UserPoolClientId': 'clientId',
    'UserPoolId': 'userPoolId',
    'Region': 'region',
    'MaxUploadBytes': 'maxUploadBytes',
}


def load_stack_outputs(path: Path) -> Dict[str, str]:
    """Read ``describe-stacks`` outputs saved as JSON.

    Accepts either the ``Stacks[0].Outputs`` list or the full
    ``describe-stacks`` response.
    """
    data = json.loads(path.read_text(encoding='utf-8'))
    if isinstance(data, dict) and 'Stacks' in data:
        data = data['Stacks'][0].get('Outputs', [])
    return {item['OutputKey']: item['OutputValue'] for item in data or []}


def build_web_config(outputs: Dict[str, str]) -> Dict[str, object]:
    """Map stack outputs to the browser configuration object.

    Raises:
        KeyError: If a required output is missing.
    """
    missing = [key for key in WEB_CONFIG_OUTPUTS if not outputs.get(key)]
    if missing:
        raise KeyError('Web stack outputs are missing: ' + ', '.join(missing))
    config: Dict[str, object] = {
        name: outputs[key] for key, name in WEB_CONFIG_OUTPUTS.items()
    }
    config['apiUrl'] = str(config['apiUrl']).rstrip('/')
    config['maxUploadBytes'] = int(config['maxUploadBytes'])
    return config


def render_web(outputs_file: Path, templates: Path, out: Path) -> List[Path]:
    """Copy the web templates to ``out`` and write ``config.js``.

    Args:
        outputs_file: JSON file with the web stack outputs.
        templates: The ``web/templates`` directory.
        out: Output directory; replaced if it exists.

    Returns:
        The files written.
    """
    config = build_web_config(load_stack_outputs(outputs_file))
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(templates, out)
    config_js = out / 'config.js'
    config_js.write_text(
        '// Generated by scripts/deploy_helper.py from the stack outputs. '
        'Do not edit.\n'
        f'window.RFP_CONFIG = {json.dumps(config, indent=2)};\n',
        encoding='utf-8',
    )
    return sorted(p for p in out.rglob('*') if p.is_file())


def main(argv: Optional[List[str]] = None) -> int:
    """Parse arguments and run a subcommand."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest='command', required=True)

    web = sub.add_parser('render-web',
                         help='Render the static site with config.js')
    web.add_argument('--outputs', type=Path, required=True,
                     help='JSON file with the web stack outputs')
    web.add_argument('--templates', type=Path, required=True)
    web.add_argument('--out', type=Path, required=True)

    args = parser.parse_args(argv)
    try:
        if args.command == 'render-web':
            files = render_web(args.outputs, args.templates, args.out)
            print(f'Rendered {len(files)} web files into {args.out}')
    except (KeyError, OSError, ValueError) as error:
        print(f'ERROR: {error}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
