#!/bin/bash
# Writes frontend/src/config.js (gitignored) from the deployed stack outputs:
# CloudFront URL from the frontend stack, Cognito IDs from the auth stack.
# phase4-frontend.sh runs this; run it yourself before rebuilding the frontend
# for an update, otherwise the build uses the placeholders from config.example.js.
#
# Usage: ./generate-frontend-config.sh [stack-name] [region]
set -e

STACK_NAME=${1:-bankiq}
REGION=${AWS_DEFAULT_REGION:-${2:-$(aws configure get region 2>/dev/null || echo "us-east-1")}}

SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"

stack_output() {
  aws cloudformation describe-stacks --stack-name "$1" --region "$REGION" \
    --query "Stacks[0].Outputs[?OutputKey==\`$2\`].OutputValue" --output text
}

CLOUDFRONT_URL=$(stack_output "${STACK_NAME}-frontend" ApplicationUrl)
COGNITO_USER_POOL_ID=$(stack_output "${STACK_NAME}-auth" UserPoolId)
COGNITO_CLIENT_ID=$(stack_output "${STACK_NAME}-auth" UserPoolClientId)
COGNITO_DOMAIN=$(stack_output "${STACK_NAME}-auth" CognitoDomain)

# Never write empty values: a missing stack output would ship a broken login.
for v in CLOUDFRONT_URL COGNITO_USER_POOL_ID COGNITO_CLIENT_ID COGNITO_DOMAIN; do
  if [ -z "${!v}" ] || [ "${!v}" = "None" ]; then
    echo "ERROR: could not read $v from the ${STACK_NAME}-frontend / ${STACK_NAME}-auth stacks in $REGION" >&2
    exit 1
  fi
done

cat > "${SCRIPT_DIR}/../../frontend/src/config.js" << EOF
// Auto-generated by cfn/scripts/generate-frontend-config.sh - CloudFront + ECS Backend + Cognito Auth
// This file is gitignored; do not commit it.
export const API_URL = '$CLOUDFRONT_URL';
export const ENVIRONMENT = 'production';
export const CLOUDFRONT_URL = '$CLOUDFRONT_URL';

export const cognitoConfig = {
  region: '$REGION',
  userPoolId: '$COGNITO_USER_POOL_ID',
  userPoolWebClientId: '$COGNITO_CLIENT_ID',
  oauth: {
    domain: '$COGNITO_DOMAIN.auth.$REGION.amazoncognito.com',
    scope: ['email', 'openid', 'profile'],
    redirectSignIn: '$CLOUDFRONT_URL',
    redirectSignOut: '$CLOUDFRONT_URL',
    responseType: 'code'
  }
};
EOF

echo "✅ Wrote frontend/src/config.js for ${STACK_NAME} in ${REGION}"
